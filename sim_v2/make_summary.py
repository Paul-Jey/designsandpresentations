"""Write results_summary.md from results.json (no hand-typed numbers)."""
import json
from pathlib import Path

import yaml

HERE = Path(__file__).parent
R = json.load(open(HERE / "results.json"))
C = yaml.safe_load(open(HERE / "assumptions.yaml"))
rd, s5, s8, s9 = R["reference_day"], R["S5"], R["S8"], R["S9"]
a = s5["annual"]
f0 = lambda x: f"{x:,.0f}"
f1 = lambda x: f"{x:,.1f}"
f2 = lambda x: f"{x:,.2f}"

L = []
w = L.append
w("# results_summary.md — model v2 (MODELLED)\n")
w("Generated by `make_summary.py` from `results.json`. Do not edit numbers by hand; rerun `run_all.py` then this script.\n")
w(f"Seed {C['meta']['seed']} · Δt {C['meta']['dt_s']} s · {C['meta']['days_per_year']} working days/yr · "
  f"tariff ₹{C['tariff']['energy_rs_per_kwh']}/kWh + ₹{C['tariff']['demand_rs_per_kva_month']}/kVA/month · "
  f"EF {C['carbon']['ef_kg_per_kwh']} kg/kWh · T1 {C['control']['T1_min']} min · T2 {C['control']['T2_min']} min\n")

w("## Headline (Monte-Carlo, use these in report and deck)\n")
w("| Quantity | Value |\n|---|---|")
w(f"| Mean shop energy, baseline → controlled | {f0(s5['mean_E_base_kwh'])} → {f0(s5['mean_E_ctrl_kwh'])} kWh/day |")
w(f"| Mean saving | {f1(s5['mean_pct'])} % ({f0(a['e_save_day'])} kWh/day) |")
w(f"| P5 / median / P95 | {f1(s5['p5_pct'])} / {f1(s5['p50_pct'])} / {f1(s5['p95_pct'])} % |")
w(f"| Days with positive saving | {f1(s5['positive_days_pct'])} % of {s5['days']:,} |")
w(f"| Annual energy avoided | {f0(a['kwh'])} kWh/yr |")
w(f"| Annual ₹ saving, energy | ₹{f0(a['rs_energy'])}/yr |")
w(f"| Annual ₹ saving, demand charge | ₹{f0(a['rs_demand'])}/yr |")
w(f"| Annual ₹ saving, total | ₹{f0(a['rs_total'])}/yr (₹{f2(a['rs_total'] / 1e5)} lakh) |")
w(f"| CO₂ avoided | {f1(a['co2_t'])} t/yr |")
w(f"| Mean max demand, baseline → controlled | {f1(s5['md_base_mean'])} → {f1(s5['md_ctrl_mean'])} kVA |")
w(f"| Mean load factor, baseline → controlled | {f2(s5['lf_base_mean'])} → {f2(s5['lf_ctrl_mean'])} |")
w(f"| Idle-energy ratio (EnPI), baseline → controlled | {f1(100 * s5['ier_base_mean'])} → {f1(100 * s5['ier_ctrl_mean'])} % |")
w(f"| Nuisance standby events | {f2(s5['nuisance_per_machine_shift'])} per machine-shift |")
w(f"| False standby (operator present, unseen) | {s5['false_standby_per_machine_shift']:.4f} per machine-shift |")
w(f"| Full-shop cost incl. actuation + integration (CCTV reused) | ₹{f0(s8['full_shop_cost_rs'])} → payback {f1(s8['full_shop_payback_months'])} months |")
w(f"| Same with new IP cameras | ₹{f0(s8['full_shop_cost_new_cams_rs'])} → payback {f1(s8['full_shop_payback_new_cams_months'])} months |")
w(f"| Node's own electricity | {f0(s8['node_kwh_yr'])} kWh/yr = {f2(s8['node_share_of_saving_pct'])} % of the saving |")
w("")

w("## Saving by load type (Monte-Carlo mean, kWh/day)\n")
w("| Load | kWh/day saved |\n|---|---|")
for k, v in s5["by_load_saving_kwh_day"].items():
    w(f"| {k} | {f1(v)} |")
w("")

w("## S1 One machine, one shift (reference day)\n")
s1 = R["S1"]
w(f"M{s1['machine'] + 1}, {s1['shift']}: {f1(s1['E_base_kwh'])} → {f1(s1['E_ctrl_kwh'])} kWh ({f1(s1['saving_pct'])} %).\n")

w("## S2 / S3 Reference day (one simulated day, seed fixed)\n")
w(f"Shop: {f0(rd['E_base_kwh'])} → {f0(rd['E_ctrl_kwh'])} kWh ({f1(rd['saving_pct'])} %). "
  f"Standby entries {rd['standby_events']}, nuisance {rd['nuisance_events']}, warm-up energy charged {f1(rd['warmup_kwh'])} kWh.\n")
w("| Load | Baseline kWh | Controlled kWh | Saving % |\n|---|---|---|---|")
for k, v in R["S3"].items():
    w(f"| {k} | {f0(v['base'])} | {f0(v['ctrl'])} | {f1(v['saving_pct'])} |")
w("\nNote: the reference day saves more than the Monte-Carlo mean; quote the Monte-Carlo mean as the headline.\n")

s4 = R["S4"]
w("## S4 Load-duration, load factor, maximum demand (reference day)\n")
w("| | Baseline | Controlled |\n|---|---|---|")
w(f"| Average power | {f1(s4['avg_base_kw'])} kW | {f1(s4['avg_ctrl_kw'])} kW |")
w(f"| Peak power | {f1(s4['peak_base_kw'])} kW | {f1(s4['peak_ctrl_kw'])} kW |")
w(f"| Load factor | {f2(s4['lf_base'])} | {f2(s4['lf_ctrl'])} |")
w(f"| Max demand (15 min, PF 0.9) | {f1(s4['md_base_kva'])} kVA | {f1(s4['md_ctrl_kva'])} kVA |")
w("\nHonest claim: energy falls; peak and MD barely move because the peak happens when every machine is cutting. Load factor falls because average falls while peak stays.\n")

w("## S6 Sensitivity (annual ₹, energy + demand; 150 days per case)\n")
w(f"Reference (150-day run): ₹{f0(R['S6']['reference_rs'])}/yr\n")
w("| Input (low / high) | ₹/yr at low input | ₹/yr at high input |\n|---|---|---|")
for c in reversed(R["S6"]["cases"]):
    w(f"| {c['name']} | {f0(c['low_input_rs'])} | {f0(c['high_input_rs'])} |")
w("")

w("## S7 Timer study (150 days per point)\n")
w("| T1 (min) | Saving % | Nuisance / machine-shift | False standby / machine-shift |\n|---|---|---|---|")
for r in R["S7"]:
    w(f"| {r['T1_min']} | {f2(r['saving_pct'])} | {f2(r['nuisance_per_machine_shift'])} | {r['false_standby_per_machine_shift']:.4f} |")
w("\nReading: nuisance standbys peak when T1 sits just under the 15-min tea break (machine sleeps, operator returns within 5 min). "
  "T1 = 3 min gives more saving and fewer nuisance events than T1 = 5 to 10 min; T1 ≤ 1 min raises false standbys. Chosen T1 = 3 min. "
  "Better still: send a planned pause (PROFIenergy) at the start of scheduled breaks.\n")

w("## S8 Payback per node (net of node electricity)\n")
w(f"Shop-average saving per machine: ₹{f0(s8['rs_per_machine_yr'])}/yr. Node draws {f0(s8['node_kwh_yr'])} kWh/yr.\n")
w("| Machines per node | Cost (CCTV reused) | Payback (months) | Cost (new cameras) | Payback (months) |\n|---|---|---|---|---|")
reuse = {r["machines"]: r for r in s8["rows"] if r["reuse_cctv"]}
new = {r["machines"]: r for r in s8["rows"] if not r["reuse_cctv"]}
for n in sorted(reuse):
    w(f"| {n} | ₹{f0(reuse[n]['cost_rs'])} | {f1(reuse[n]['payback_months'])} | ₹{f0(new[n]['cost_rs'])} | {f1(new[n]['payback_months'])} |")
w("\nCaveat: per-node rows exclude actuation hardware for shared loads and integration labour; the full-shop row in the headline includes them.\n")

w("## S9 Office case (model v1, kept for generality)\n")
w(f"{f1(s9['E_base'])} → {f1(s9['E_ctrl'])} kWh/day, {f1(s9['saving_pct'])} %, {f0(s9['annual_kwh'])} kWh/yr, "
  f"₹{f0(s9['gross_rs'])}/yr gross, ₹{f0(s9['net_rs'])}/yr net of node, node retains {f1(s9['net_retained_pct'])} %. "
  f"Payback {f1(s9['payback_gross_months'])} months gross → **{f1(s9['payback_net_months'])} months net** (corrected from Review 3).\n")

w("## Figures\n")
for f in sorted((HERE / "figures").glob("*.png")):
    w(f"- `figures/{f.name}`")
(HERE / "results_summary.md").write_text("\n".join(L) + "\n")
print("written")
